import { Ionicons } from "@expo/vector-icons";
import * as Print from "expo-print";
import { router } from "expo-router";
import * as Sharing from "expo-sharing";
import { useCallback, useEffect, useState } from "react";
import { ActivityIndicator, ScrollView, StyleSheet, Text, TouchableOpacity, View } from "react-native";
import { SafeAreaView } from "react-native-safe-area-context";

import { NutrientBar } from "@/src/components/NutrientBar";
import { api, type WeeklyReport } from "@/src/lib/api";
import { useAuth } from "@/src/lib/auth-context";
import { useLang } from "@/src/lib/language-context";
import { COLORS, FONT, SIZE, TIER_META } from "@/src/theme";

const DAY_LABELS = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];

export default function ReportScreen() {
  const { t } = useLang();
  const { user } = useAuth();
  const [report, setReport] = useState<WeeklyReport | null>(null);
  const [loading, setLoading] = useState(true);
  const [sharing, setSharing] = useState(false);

  const load = useCallback(async () => {
    setLoading(true);
    try {
      const r = await api.weeklyReport();
      setReport(r);
    } catch {
      setReport(null);
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    void load();
  }, [load]);

  const maxDay = report ? Math.max(1, ...report.days.map((d) => d.green + d.yellow + d.red)) : 1;

  const buildHtml = (r: WeeklyReport): string => {
    const rows = r.days
      .map((d, i) => {
        const total = d.green + d.yellow + d.red;
        return `<tr>
          <td>${DAY_LABELS[i]}</td><td>${d.date}</td>
          <td style="color:#059669">${d.green}</td>
          <td style="color:#D97706">${d.yellow}</td>
          <td style="color:#DC2626">${d.red}</td>
          <td><b>${total}</b></td>
        </tr>`;
      })
      .join("");
    const stage = user?.stage === "dialysis" ? "On Dialysis" : user?.stage === "pre_dialysis" ? "Pre-dialysis CKD" : "Not specified";
    return `<!doctype html>
<html><head><meta charset="utf-8"/><title>Renal Diet Weekly Report</title>
<style>
  body{font-family:-apple-system,BlinkMacSystemFont,Segoe UI,sans-serif;color:#1C1917;padding:32px;}
  h1{color:#2F5233;margin:0 0 4px}
  .sub{color:#57534E;margin-bottom:24px}
  .grid{display:flex;gap:12px;margin:16px 0}
  .box{flex:1;padding:16px;border-radius:12px;border:2px solid}
  .g{background:#D1FAE5;border-color:#34D399}
  .y{background:#FEF3C7;border-color:#F59E0B}
  .r{background:#FEE2E2;border-color:#F87171}
  .num{font-size:28px;font-weight:800}
  table{width:100%;border-collapse:collapse;margin-top:16px}
  th,td{padding:8px;border-bottom:1px solid #E7E5E4;text-align:left}
  th{background:#F5F5F4}
  h2{margin-top:24px;color:#2F5233}
  ul{padding-left:20px}
  .foot{margin-top:32px;font-size:12px;color:#78716C}
</style></head>
<body>
  <h1>Indian Renal Diet — Weekly Report</h1>
  <div class="sub">Patient: <b>${user?.full_name || user?.email}</b> · Stage: <b>${stage}</b><br>
    Week of ${r.start_date} to ${r.end_date}</div>

  <div class="grid">
    <div class="box g"><div>Safe meals</div><div class="num">${r.green}</div></div>
    <div class="box y"><div>Caution meals</div><div class="num">${r.yellow}</div></div>
    <div class="box r"><div>Avoid meals</div><div class="num">${r.red}</div></div>
  </div>

  <p><b>Total meals logged:</b> ${r.total_meals}</p>

  <table>
    <tr><th>Day</th><th>Date</th><th>Safe</th><th>Caution</th><th>Avoid</th><th>Total</th></tr>
    ${rows}
  </table>

  <h2>Top safe foods</h2>
  <ul>${r.top_safe_foods.length ? r.top_safe_foods.map((f) => `<li>${f}</li>`).join("") : "<li>—</li>"}</ul>

  <h2>Foods to reduce</h2>
  <ul>${r.top_avoid_foods.length ? r.top_avoid_foods.map((f) => `<li>${f}</li>`).join("") : "<li>—</li>"}</ul>

  <h2>Average daily nutrients</h2>
  <table>
    <tr><th>Nutrient</th><th>Average</th><th>Daily limit</th><th>%</th></tr>
    <tr><td>Potassium</td><td>${Math.round(r.avg_daily.potassium_mg)} mg</td><td>${r.limits.potassium_mg} mg</td><td>${Math.round((r.avg_daily.potassium_mg * 100) / r.limits.potassium_mg)}%</td></tr>
    <tr><td>Phosphorus</td><td>${Math.round(r.avg_daily.phosphorus_mg)} mg</td><td>${r.limits.phosphorus_mg} mg</td><td>${Math.round((r.avg_daily.phosphorus_mg * 100) / r.limits.phosphorus_mg)}%</td></tr>
    <tr><td>Sodium</td><td>${Math.round(r.avg_daily.sodium_mg)} mg</td><td>${r.limits.sodium_mg} mg</td><td>${Math.round((r.avg_daily.sodium_mg * 100) / r.limits.sodium_mg)}%</td></tr>
    <tr><td>Protein</td><td>${r.avg_daily.protein_g.toFixed(1)} g</td><td>—</td><td>—</td></tr>
  </table>

  <div class="foot">
    Generated by Indian Renal Diet mobile app. General guidance only —
    please review this report with your nephrologist.
  </div>
</body></html>`;
  };

  const share = async () => {
    if (!report || sharing) return;
    setSharing(true);
    try {
      const { uri } = await Print.printToFileAsync({ html: buildHtml(report) });
      if (await Sharing.isAvailableAsync()) {
        await Sharing.shareAsync(uri, { mimeType: "application/pdf", dialogTitle: "Share Weekly Report" });
      }
    } finally {
      setSharing(false);
    }
  };

  if (loading) {
    return (
      <SafeAreaView style={styles.safe}>
        <View style={styles.center}><ActivityIndicator size="large" color={COLORS.brand} /></View>
      </SafeAreaView>
    );
  }

  if (!report || report.total_meals === 0) {
    return (
      <SafeAreaView style={styles.safe} edges={["top", "bottom"]}>
        <View style={styles.topBar}>
          <TouchableOpacity testID="report-back" onPress={() => router.back()} style={styles.backBtn}>
            <Ionicons name="chevron-back" size={26} color={COLORS.textPrimary} />
            <Text style={styles.backText}>{t("back")}</Text>
          </TouchableOpacity>
        </View>
        <View style={styles.center}>
          <Ionicons name="document-text-outline" size={48} color={COLORS.textSecondary} />
          <Text style={styles.empty}>{t("reportEmpty")}</Text>
        </View>
      </SafeAreaView>
    );
  }

  return (
    <SafeAreaView style={styles.safe} edges={["top", "bottom"]}>
      <View style={styles.topBar}>
        <TouchableOpacity testID="report-back" onPress={() => router.back()} style={styles.backBtn}>
          <Ionicons name="chevron-back" size={26} color={COLORS.textPrimary} />
          <Text style={styles.backText}>{t("back")}</Text>
        </TouchableOpacity>
      </View>

      <ScrollView contentContainerStyle={styles.container}>
        <Text style={styles.title}>{t("weeklyReport")}</Text>
        <Text style={styles.subtitle}>{t("reportForNephro")}</Text>
        <Text style={styles.range}>{t("weekOf")} {report.start_date} → {report.end_date}</Text>

        <View style={styles.pillsRow}>
          <Pill count={report.green} label={t("summarySafe")} tier="GREEN" />
          <Pill count={report.yellow} label={t("summaryCaution")} tier="YELLOW" />
          <Pill count={report.red} label={t("summaryAvoid")} tier="RED" />
        </View>

        <View style={styles.card}>
          <Text style={styles.cardTitle}>{t("totalMeals")}: {report.total_meals}</Text>
          <View style={styles.chart}>
            {report.days.map((d, i) => {
              const g = d.green, y = d.yellow, r = d.red;
              return (
                <View testID={`day-bar-${d.date}`} key={d.date} style={styles.dayCol}>
                  <View style={styles.barTrack}>
                    {r > 0 && <View style={[styles.bar, { flexBasis: 20, backgroundColor: COLORS.redStrong, height: `${Math.min(100, (r / maxDay) * 100)}%` }]} />}
                    {y > 0 && <View style={[styles.bar, { backgroundColor: COLORS.yellowStrong, height: `${Math.min(100, (y / maxDay) * 100)}%` }]} />}
                    {g > 0 && <View style={[styles.bar, { backgroundColor: COLORS.greenStrong, height: `${Math.min(100, (g / maxDay) * 100)}%` }]} />}
                  </View>
                  <Text style={styles.dayLabel}>{DAY_LABELS[i]}</Text>
                </View>
              );
            })}
          </View>
        </View>

        {report.top_safe_foods.length > 0 && (
          <View style={styles.card}>
            <Text style={[styles.cardTitle, { color: COLORS.greenStrong }]}>{t("topSafe")}</Text>
            {report.top_safe_foods.map((n) => (
              <Text key={n} style={styles.listItem}>• {n}</Text>
            ))}
          </View>
        )}

        {report.top_avoid_foods.length > 0 && (
          <View style={styles.card}>
            <Text style={[styles.cardTitle, { color: COLORS.redStrong }]}>{t("topAvoid")}</Text>
            {report.top_avoid_foods.map((n) => (
              <Text key={n} style={styles.listItem}>• {n}</Text>
            ))}
          </View>
        )}

        <View testID="avg-nutrient-card" style={styles.card}>
          <Text style={styles.cardTitle}>{t("avgDaily")}</Text>
          <Text style={styles.avgSub}>{t("avgVsLimit")}</Text>
          <View style={{ gap: 14, marginTop: 8 }}>
            <NutrientBar
              testID="avg-potassium"
              label={t("nutrientPotassium")}
              value={report.avg_daily.potassium_mg}
              limit={report.limits.potassium_mg}
            />
            <NutrientBar
              testID="avg-phosphorus"
              label={t("nutrientPhosphorus")}
              value={report.avg_daily.phosphorus_mg}
              limit={report.limits.phosphorus_mg}
            />
            <NutrientBar
              testID="avg-sodium"
              label={t("nutrientSodium")}
              value={report.avg_daily.sodium_mg}
              limit={report.limits.sodium_mg}
            />
          </View>
        </View>

        <TouchableOpacity
          testID="share-report-button"
          style={[styles.shareBtn, sharing && { opacity: 0.6 }]}
          onPress={share}
          disabled={sharing}
        >
          <Ionicons name="share-social" size={22} color={COLORS.textInverse} />
          <Text style={styles.shareText}>{sharing ? "..." : t("share")}</Text>
        </TouchableOpacity>
      </ScrollView>
    </SafeAreaView>
  );
}

function Pill({ count, label, tier }: { count: number; label: string; tier: "GREEN" | "YELLOW" | "RED" }) {
  const meta = TIER_META[tier];
  return (
    <View style={[styles.pill, { backgroundColor: meta.bg, borderColor: meta.border }]}>
      <Text style={[styles.pillNum, { color: meta.text }]}>{count}</Text>
      <Text style={[styles.pillLabel, { color: meta.text }]}>{label}</Text>
    </View>
  );
}

const styles = StyleSheet.create({
  safe: { flex: 1, backgroundColor: COLORS.bgDefault },
  topBar: { padding: SIZE.m, paddingBottom: 0 },
  backBtn: { flexDirection: "row", alignItems: "center", gap: 4, alignSelf: "flex-start" },
  backText: { fontSize: FONT.bodyL, fontWeight: "600", color: COLORS.textPrimary },
  container: { padding: SIZE.m, gap: SIZE.m, paddingBottom: SIZE.xxl },
  center: { flex: 1, alignItems: "center", justifyContent: "center", gap: SIZE.m, padding: SIZE.l },
  empty: { fontSize: FONT.bodyL, color: COLORS.textSecondary, textAlign: "center" },
  title: { fontSize: FONT.h1, fontWeight: "800", color: COLORS.textPrimary },
  subtitle: { fontSize: FONT.body, color: COLORS.textSecondary },
  range: { fontSize: FONT.body, color: COLORS.textPrimary, fontWeight: "600" },
  pillsRow: { flexDirection: "row", gap: SIZE.s, marginTop: SIZE.s },
  pill: { flex: 1, alignItems: "center", padding: 12, borderWidth: 2, borderRadius: SIZE.radiusMd },
  pillNum: { fontSize: 28, fontWeight: "800" },
  pillLabel: { fontSize: FONT.label, fontWeight: "700", marginTop: 2 },
  card: { backgroundColor: COLORS.bgSurface, borderRadius: SIZE.radiusLg, padding: SIZE.m, borderWidth: 1, borderColor: COLORS.border, gap: 6 },
  cardTitle: { fontSize: FONT.bodyL, fontWeight: "800", color: COLORS.textPrimary },
  chart: { flexDirection: "row", justifyContent: "space-between", alignItems: "flex-end", height: 140, marginTop: 8 },
  dayCol: { alignItems: "center", flex: 1, gap: 6 },
  barTrack: { width: 26, height: 100, backgroundColor: COLORS.bgAlt, borderRadius: 6, justifyContent: "flex-end", overflow: "hidden", flexDirection: "column-reverse" },
  bar: { width: "100%" },
  dayLabel: { fontSize: 12, color: COLORS.textSecondary, fontWeight: "600" },
  listItem: { fontSize: FONT.body, color: COLORS.textPrimary },
  avgSub: { fontSize: FONT.label, color: COLORS.textSecondary },
  shareBtn: {
    flexDirection: "row",
    alignItems: "center",
    justifyContent: "center",
    gap: 8,
    height: SIZE.touchPrimary,
    borderRadius: SIZE.radiusPill,
    backgroundColor: COLORS.brand,
    marginTop: SIZE.s,
  },
  shareText: { color: COLORS.textInverse, fontSize: FONT.bodyL, fontWeight: "700" },
});
